def load_runtime_catalog():
    source = RUNTIME_CATALOG.read_text(encoding="utf-8")
    marker = "window.THF_EXERCISES = "
    start = source.index(marker) + len(marker)
    end = source.rfind(";")
    return json.loads(source[start:end].strip())


class RuntimeBilingualStepAlignmentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.by_id = {item["id"]: item for item in load_runtime_catalog()}

    def test_seven_reviewed_runtime_cues_match_exact_bilingual_copy(self):
        for exercise_id, expected_ar in EXPECTED_AR.items():
            with self.subTest(exercise_id=exercise_id):
                item = self.by_id[exercise_id]
                self.assertEqual(expected_ar, item["steps"]["ar"])
                self.assertEqual(len(item["steps"]["en"]), len(item["steps"]["ar"]))

    def test_unrelated_runtime_exercises_remain_present(self):
        self.assertEqual(112, len(self.by_id))
        self.assertTrue(set(EXPECTED_AR).issubset(self.by_id))


if __name__ == "__main__":
    unittest.main()
